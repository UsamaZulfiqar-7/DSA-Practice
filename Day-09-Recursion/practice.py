# Day 9 — Recursion Practice

# 1. Print numbers from 1 to n recursively.
# 2. Calculate factorial recursively. Example: 5 -> 120.
# 3. Find sum of digits. Example: 1234 -> 10.
# 4. Calculate x^n recursively. Example: 2,5 -> 32.
# 5. Reverse a string recursively. Example: hello -> olleh.
# 6. Check whether a string is a palindrome.
# 7. Return the nth Fibonacci number recursively.
# 8. Implement recursive binary search on a sorted array.
# 9. Implement Euclid's GCD recursively. Example: gcd(48,18) -> 6.
# 10. Generate all subsequences of a string using recursion/backtracking.

# Targets:
# factorial O(n), digit sum O(number of digits), reverse O(n), palindrome O(n),
# binary search O(log n), GCD O(log(min(a,b))) approximately, subsequences O(2^n) outputs.
