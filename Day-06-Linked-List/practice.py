# Day 6 — Linked List Practice

# Try these yourself before checking solutions.py.

# 1. Create a linked list: 10 -> 20 -> 30 -> None.
# 2. Write a function to display all nodes.
# 3. Find the length of a linked list.
# 4. Search for a value and return its position, or -1.
# 5. Insert a new node at the beginning.
# 6. Insert a new node at the end.
# 7. Delete the first occurrence of a given value.
# 8. Reverse a linked list in-place.
# 9. Find the middle node using slow and fast pointers.
# 10. Detect a cycle using Floyd's cycle detection algorithm.

# Target complexities:
# Search: O(n)
# Length: O(n)
# Insert beginning: O(1)
# Reverse: O(n) time, O(1) extra space
# Find middle: O(n) time, O(1) extra space
# Detect cycle: O(n) time, O(1) extra space
